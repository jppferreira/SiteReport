/** Widen string leaves so other locales can diverge without fighting `as const` literals. */
type DeepStringLeaves<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly (infer U)[]
      ? readonly DeepStringLeaves<U>[]
      : T[K] extends object
        ? DeepStringLeaves<T[K]>
        : T[K];
};

export default enUS;
export type TranslationTree = DeepStringLeaves<typeof enUS>;
